#Assignment operator
a = 5
a += 3 # a = a + 3 = 8
print("ans:",a)
a -= 3 # a = a - 3 = 5
print("ans:",a)
a *= 3 # a = a * 3 = 15
print("ans:",a)
a /= 3 # a = a / 3 = 5.0
print("ans:",a)
a //= 3 # a = a // 3 =  1.0
print("ans:",a)
a **= 3 # a = a ** 3 = 1.0
print("ans:",a)        



















